#!/usr/bin/env node
/**
 * Rebuild js/data/furigana.js.
 *
 * Tokenizes every piece of Japanese text in the question banks with kuromoji
 * (node_modules/kuromoji/dict, loaded at build time only) and emits a
 * [surface, hiragana reading] pair for every token whose surface contains
 * kanji. Existing hand-curated pairs are kept; kuromoji fills the gaps.
 *
 * Run: node tools/build-furigana.js
 */

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const kuromoji = require("kuromoji");

const BANKS = [
  "js/data/bank-n5.js",
  "js/data/bank-n5-large.js",
  "js/data/bank-n5-past.js",
  "js/data/bank-n5-2021-12.js",
  "js/data/bank-n5-web.js",
  "js/data/bank-n4.js"
];

const KANJI_RE = /[\u4e00-\u9fff]/;

function kataToHira(s) {
  return String(s).replace(/[\u30a1-\u30f6]/g, (c) =>
    String.fromCharCode(c.charCodeAt(0) - 0x60));
}

function loadTexts() {
  const texts = new Set();
  BANKS.forEach((file) => {
    const sandbox = { window: {} };
    vm.runInNewContext(fs.readFileSync(file, "utf8"), sandbox, { filename: file });
    const banks = sandbox.window.JLPT_BANKS || {};
    Object.keys(banks).forEach((key) => {
      (banks[key] || []).forEach((q) => {
        [q.prompt, q.passage, q.kana, q.exp, q.exp_jp].forEach((t) => {
          if (typeof t === "string" && KANJI_RE.test(t)) texts.add(t);
        });
        if (Array.isArray(q.options)) q.options.forEach((o) => {
          if (typeof o === "string" && KANJI_RE.test(o)) texts.add(o);
        });
        if (q.starData) [q.starData.before, q.starData.after].concat(q.starData.ordered || []).forEach((t) => {
          if (typeof t === "string" && KANJI_RE.test(t)) texts.add(t);
        });
      });
    });
  });
  return texts;
}

function main() {
  const dictPath = path.join(__dirname, "..", "node_modules", "kuromoji", "dict");
  kuromoji.builder({ dicPath: dictPath }).build((err, tokenizer) => {
    if (err) { console.error(err); process.exit(1); }

    const current = { window: {} };
    vm.runInNewContext(fs.readFileSync(path.join(__dirname, "..", "js/data/furigana.js"), "utf8"),
      current, { filename: "furigana.js" });
    const pairs = new Map(current.window.JLPT_FURIGANA_PAIRS.map((p) => [p[0], p[1]]));
    const kept = pairs.size;

    let added = 0;
    const texts = loadTexts();
    texts.forEach((text) => {
      tokenizer.tokenize(text).forEach((token) => {
        const surface = token.surface_form;
        if (!surface || !KANJI_RE.test(surface)) return;
        if (!token.reading || token.reading === "*") return;
        const reading = kataToHira(token.reading);
        if (reading === surface) return;
        if (/[<>&\s]/.test(surface)) return;
        if (!pairs.has(surface)) { pairs.set(surface, reading); added += 1; }
      });
    });

    const sorted = Array.from(pairs).sort((a, b) => b[0].length - a[0].length || a[0].localeCompare(b[0], "ja"));
    const lines = sorted.map(([w, r]) => "    [" + JSON.stringify(w) + ", " + JSON.stringify(r) + "]");
    const out = "/* Extracted, validated question data. Generated by tools/build-furigana.js — do not edit by hand;\n"
      + "   hand additions survive rebuilds. */\n"
      + "window.JLPT_FURIGANA_PAIRS = [\n" + lines.join(",\n") + "\n];\n";
    fs.writeFileSync(path.join(__dirname, "..", "js/data/furigana.js"), out);
    console.log("furigana pairs: kept " + kept + ", added " + added + ", total " + sorted.length);
  });
}

main();
